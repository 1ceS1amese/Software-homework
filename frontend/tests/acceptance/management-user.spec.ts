import { expect, test } from '@playwright/test'
import { api, database, login } from './helpers'

test('REL-03 用户页面管理、一次性密码、角色与旧令牌即时失效', async ({ page }, info) => {
  await login(page, 'admin'); await page.goto('/admin/users')
  const username = `user-${info.project.name}-${Date.now() % 1000000}`
  await page.getByRole('button', { name: '新增用户', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('登录名', { exact: true }).fill(username)
  await dialog.getByLabel('姓名', { exact: true }).fill('用户管理验收')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  const credentialDialog = page.getByRole('dialog', { name: '一次性初始密码' })
  await expect(credentialDialog).toBeVisible()
  const password = (await credentialDialog.getByTestId('initial-password').innerText()).trim()
  expect(password.length).toBeGreaterThanOrEqual(20)
  await credentialDialog.getByRole('button', { name: '已安全保存' }).click()
  await page.getByPlaceholder('输入关键词').fill(username)
  await page.getByRole('button', { name: '查询', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: username })
  await expect(row).toBeVisible()
  const id = Number(database(`SELECT id FROM sys_user WHERE username='${username}'`))
  expect(database(`SELECT CONCAT(must_change_pwd, '|', password LIKE '$2%') FROM sys_user WHERE id=${id}`)).toBe('1|1')
  const loginResponse = await page.request.post('/api/auth/login', { data: { username, password } })
  const token = (await loginResponse.json()).data
  const own = (path: string) => page.request.get('/api' + path, { headers: { Authorization: `Bearer ${token}` } })
  expect((await own('/auth/me')).status()).toBe(200)
  await row.getByRole('button', { name: '编辑', exact: true }).click()
  await dialog.getByLabel('姓名', { exact: true }).fill('已编辑用户')
  await dialog.getByRole('button', { name: '保存', exact: true }).click(); await expect(dialog).not.toBeVisible()
  expect((await own('/auth/me')).status()).toBe(401)
  await row.getByRole('button', { name: '分配角色', exact: true }).click()
  await dialog.getByLabel('身份', { exact: true }).selectOption('TEACHER')
  await dialog.getByRole('button', { name: '保存', exact: true }).click(); await expect(dialog).not.toBeVisible()
  expect(database(`SELECT user_type FROM sys_user WHERE id=${id}`)).toBe('TEACHER')
  await row.getByRole('button', { name: '重置密码', exact: true }).click()
  await dialog.getByRole('button', { name: '确认操作', exact: true }).click()
  await expect(credentialDialog).toBeVisible()
  const reset = (await credentialDialog.getByTestId('initial-password').innerText()).trim()
  expect(reset).not.toBe(password)
  await credentialDialog.getByRole('button', { name: '已安全保存' }).click()
  expect((await page.request.post('/api/auth/login', { data: { username, password } })).status()).toBe(401)
  const afterReset = await page.request.post('/api/auth/login', { data: { username, password: reset } })
  expect(afterReset.status()).toBe(200)
  const newToken = (await afterReset.json()).data
  await row.getByRole('button', { name: '停用', exact: true }).click()
  await dialog.getByRole('button', { name: '确认操作', exact: true }).click(); await expect(dialog).not.toBeVisible()
  expect((await page.request.get('/api/auth/me', { headers: { Authorization: `Bearer ${newToken}` } })).status()).toBe(401)
  expect((await api(page, '/users/1', 'DELETE')).body.code).toBe(70103)
  expect((await api(page, '/users/3', 'DELETE')).body.code).toBe(40105)
  expect((await api(page, `/users/${id}/roles`, 'PUT', { roleCodes: ['TEACHER', 'ADMIN'] })).status).toBe(400)
  await row.getByRole('button', { name: '删除', exact: true }).click()
  await dialog.getByRole('button', { name: '确认操作', exact: true }).click(); await expect(dialog).not.toBeVisible()
  expect(database(`SELECT deleted FROM sys_user WHERE id=${id}`)).toBe('1')
  expect((await api(page, '/users', 'POST', { username, realName: '注销重用' })).body.code).toBe(70102)
  expect(database(`SELECT COUNT(*) FROM sys_audit_log WHERE target_type='sys_user' AND target_id=${id} AND (CAST(before_json AS CHAR) LIKE '%$2%' OR CAST(after_json AS CHAR) LIKE '%initialPassword%')`)).toBe('0')
})
