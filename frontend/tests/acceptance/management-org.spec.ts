import { expect, test } from '@playwright/test'
import { api, database, login } from './helpers'

test('REL-01 院系专业页面增改删、关联保护、重复代码与越权拒绝', async ({ page }, info) => {
  await login(page, 'admin')
  await page.goto('/admin/depts')
  const code = `ORG-${info.project.name}-${Date.now() % 10000000}`
  await page.getByRole('button', { name: '新增院系', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('代码', { exact: true }).fill(code)
  await dialog.getByLabel('名称', { exact: true }).fill('管理验收院系')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  const dept = Number(database(`SELECT id FROM dept WHERE code='${code}'`))
  const row = page.getByRole('row').filter({ hasText: code })
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: '编辑', exact: true }).click()
  await dialog.getByLabel('名称', { exact: true }).fill('已修改院系')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.reload()
  await expect(row).toContainText('已修改院系')
  const major = await api(page, '/majors', 'POST', { code: code + 'M', name: '验收专业', deptId: dept, degreeYears: 4 })
  expect(major.body.code).toBe(0)
  expect((await api(page, '/depts', 'POST', { code, name: '重复' })).body.code).toBe(30101)
  expect((await api(page, `/depts/${dept}`, 'DELETE')).body.code).toBe(30102)
  expect((await api(page, '/majors', 'POST', { code: code + 'X', name: '非法', deptId: 999999 })).status).toBe(404)
  expect((await api(page, `/majors/${major.body.data.id}`, 'PUT', { code: code + 'M', name: '修改专业', deptId: dept, degreeYears: 5 })).body.code).toBe(0)
  await page.reload()
  const majorRow = page.getByRole('row').filter({ hasText: code + 'M' })
  await expect(majorRow).toContainText('修改专业')
  await majorRow.getByRole('button', { name: '删除', exact: true }).click()
  await dialog.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await row.getByRole('button', { name: '删除', exact: true }).click()
  await dialog.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  expect(database(`SELECT deleted FROM dept WHERE id=${dept}`)).toBe('1')
  expect(database(`SELECT GROUP_CONCAT(action ORDER BY id) FROM sys_audit_log WHERE target_type='dept' AND target_id=${dept} AND result='SUCCESS'`)).toBe('CREATE_DEPT,UPDATE_DEPT,DELETE_DEPT')
  await page.evaluate(() => localStorage.clear())
  await login(page, 'student1')
  expect((await api(page, '/depts', 'POST', { code: code + 'S', name: '禁止' })).status).toBe(403)
  expect(database(`SELECT COUNT(*) FROM dept WHERE code='${code}S'`)).toBe('0')
})
